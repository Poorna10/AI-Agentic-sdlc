"""Contract-first API definition, implementation and test authoring."""
from __future__ import annotations

import json

from ..catalog import API_META, PACKS
from ..model import AgentResult, Change, Stage
from . import Agent


class ApiSpecAgent(Agent):
    name = "api-designer"

    def run(self, ctx, stage: Stage) -> AgentResult:
        plan = ctx.get("plan")
        packs = [p for p in PACKS if p in set(plan["present_packs"]) | set(plan["todo_packs"])]
        endpoints, fields = {}, []
        for p in packs:
            for method, path, codes in PACKS[p]["endpoints"]:
                endpoints[(method, path)] = {"method": method, "path": path, "responses": codes}
            fields += API_META[p]["request_fields"]
        # additive behaviours that change documented status codes of existing endpoints
        extra = {"expiry": [("GET", "/{code}", 410)], "ratelimit": [("POST", "/api/v1/links", 429)],
                 "blocklist": [("POST", "/api/v1/links", 422)]}
        for p in packs:
            for m, path, code in extra.get(p, []):
                if code not in endpoints[(m, path)]["responses"]:
                    endpoints[(m, path)]["responses"].append(code)
        contract = {"endpoints": sorted(endpoints.values(), key=lambda e: (e["path"], e["method"])),
                    "request_schema": "CreateLinkRequest", "request_fields": sorted(set(fields)), "packs": packs}
        return AgentResult(artifacts={"api_contract": contract},
                           notes=f"{len(contract['endpoints'])} endpoints, fields {contract['request_fields']}")


class ImplementerAgent(Agent):
    name = "implementer"

    def __init__(self, generator) -> None:
        self.gen = generator

    def run(self, ctx, stage: Stage) -> AgentResult:
        plan = ctx.get("plan")
        changes: list[Change] = []
        for pack in plan["todo_packs"]:
            changes += self.gen.propose(pack, plan["params"], include="src")
        files = sorted({c.path for c in changes})
        impl = {"packs_applied": list(plan["todo_packs"]), "deferred_packs": [], "files": files,
                "generator": getattr(self.gen, "name", "unknown")}
        return AgentResult(artifacts={"implementation": impl}, changes=changes,
                           notes=f"{len(changes)} changes across {len(files)} files")


class ImplementerSafeMode(ImplementerAgent):
    """Fallback: graceful degradation. Validates each pack against policy on its own and defers
    packs that cannot be delivered safely instead of failing the whole stage."""
    name = "implementer-safe-mode"

    def run(self, ctx, stage: Stage) -> AgentResult:
        plan = ctx.get("plan")
        changes, applied, deferred = [], [], []
        for pack in plan["todo_packs"]:
            proposal = self.gen.propose(pack, plan["params"], include="src")
            blocked = any(v.action == "BLOCK" for v in ctx.policy.evaluate_changes(proposal))
            if blocked or any(r in deferred for r in PACKS[pack]["requires"]):
                deferred.append(pack)
            else:
                changes += proposal
                applied.append(pack)
        impl = {"packs_applied": applied, "deferred_packs": deferred, "files": sorted({c.path for c in changes}),
                "generator": getattr(self.gen, "name", "unknown") + " (safe-mode)"}
        return AgentResult(artifacts={"implementation": impl}, changes=changes,
                           decisions=[{"kind": "fallback", "decision": f"Safe-mode delivery: applied {applied}, deferred {deferred}",
                                       "rationale": "primary implementer exhausted its retry budget",
                                       "alternatives": ["fail the whole stage"],
                                       "tradeoff": "partial scope; release readiness will flag deferred packs"}],
                           notes=f"applied={applied} deferred={deferred}")


