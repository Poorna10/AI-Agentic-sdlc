class TestAuthorAgent(Agent):
    name = "test-author"

    def __init__(self, generator) -> None:
        self.gen = generator

    def run(self, ctx, stage: Stage) -> AgentResult:
        plan, contract = ctx.get("plan"), ctx.get("api_contract")
        changes: list[Change] = []
        for pack in plan["todo_packs"]:
            changes += self.gen.propose(pack, plan["params"], include="tests")
        gen_path = "tests/test_contract_generated.py"
        changes.append(Change(gen_path, "write", CONTRACT_TEST.format(contract=json.dumps(contract, indent=4)),
                              source="test-author"))
        files = sorted({c.path for c in changes})
        return AgentResult(artifacts={"test_suite": {"files": files, "generated": [gen_path]}},
                           changes=changes, notes=f"{len(files)} test files (1 generated from the contract)")
